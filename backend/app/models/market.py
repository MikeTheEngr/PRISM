"""
PRISM Backend — Market Data Models

Unified shape for asset price data regardless of whether it came from
CoinGecko (crypto) or Alpha Vantage (stocks). The rest of the app should
never need to know which provider a given asset came from.
"""

from pydantic import BaseModel
from typing import Optional


class AssetPrice(BaseModel):
    symbol: str
    name: str
    asset_class: str  # 'crypto' | 'stock'
    price: float
    change_24h_pct: Optional[float] = None
    volume_24h: Optional[float] = None
    market_cap: Optional[float] = None
    last_updated: str
    source: str  # 'coingecko' | 'alpha_vantage'
    is_stale: bool = False  # true if served from cache past ideal freshness


class SignalOut(BaseModel):
    symbol: str
    direction: str  # 'bullish' | 'bearish' | 'neutral'
    confidence: float
    reasoning: str
    generated_at: str
    disclaimer: str = (
        "Pattern-based signal generated by AI. Not financial advice. "
        "Markets carry risk and past patterns do not guarantee future results."
    )
